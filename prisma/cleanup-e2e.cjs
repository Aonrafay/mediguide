require("dotenv").config();
const { Client } = require("pg");
(async () => {
  const c = new Client({ connectionString: process.env.DATABASE_URL });
  await c.connect();

  // 1) E2E review
  let r = await c.query(`DELETE FROM "Review" WHERE comment LIKE '%E2E verified review%' RETURNING id`);
  console.log("reviews deleted:", r.rowCount);

  // 2) Test patient's appointments
  r = await c.query(`DELETE FROM "Appointment" WHERE "patientId" IN (SELECT id FROM "User" WHERE email = 'e2e.patient.1111@mediguide.test') RETURNING id`);
  console.log("test appointments deleted:", r.rowCount);

  // 3) All notifications (every row was generated by today's tests — seed starts empty)
  r = await c.query(`DELETE FROM "Notification"`);
  console.log("notifications deleted:", r.rowCount);

  // 4) Test patient user
  r = await c.query(`DELETE FROM "User" WHERE email = 'e2e.patient.1111@mediguide.test' RETURNING id`);
  console.log("test user deleted:", r.rowCount);

  // 5) E2E lab: clientService, request, facility
  r = await c.query(`DELETE FROM "ClientService" WHERE "facilityId" IN (SELECT id FROM "Facility" WHERE name LIKE 'E2E Diagnostics Lab%') RETURNING id`);
  console.log("clientService deleted:", r.rowCount);
  r = await c.query(`DELETE FROM "ServiceRequest" WHERE "businessName" LIKE 'E2E Diagnostics Lab%' RETURNING id`);
  console.log("serviceRequest deleted:", r.rowCount);
  r = await c.query(`DELETE FROM "Facility" WHERE name LIKE 'E2E Diagnostics Lab%' RETURNING id`);
  console.log("lab facility deleted:", r.rowCount);

  // Final state
  const checks = await c.query(`
    SELECT
      (SELECT COUNT(*)::int FROM "User") users,
      (SELECT COUNT(*)::int FROM "Appointment") appointments,
      (SELECT COUNT(*)::int FROM "Review") reviews,
      (SELECT COUNT(*)::int FROM "Notification") notifications,
      (SELECT COUNT(*)::int FROM "ServiceRequest") requests,
      (SELECT COUNT(*)::int FROM "Facility") facilities,
      (SELECT COUNT(*)::int FROM "ClientService") clients
  `);
  console.log("FINAL:", JSON.stringify(checks.rows[0]));

  const orphans = await c.query(`
    SELECT
      (SELECT COUNT(*)::int FROM "Appointment" a LEFT JOIN "User" u ON u.id=a."patientId" WHERE u.id IS NULL) orphanAppts,
      (SELECT COUNT(*)::int FROM "Review" rr LEFT JOIN "User" u ON u.id=rr."patientId" WHERE u.id IS NULL) orphanReviews,
      (SELECT COUNT(*)::int FROM "ClientService" cs LEFT JOIN "Facility" f ON f.id=cs."facilityId" WHERE f.id IS NULL) orphanClients
  `);
  console.log("ORPHANS:", JSON.stringify(orphans.rows[0]));

  await c.end();
})().catch(e => { console.error("CLEANUP FAILED:", e.message); process.exit(1); });
